// Rebuild the offline course's downloadable source after editing the example.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../examples/student-directory');
const files = {};
function walk(folder) {
  for (const entry of fs.readdirSync(folder, {withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))) {
    if (['node_modules', 'dist', '.angular', 'out-tsc', 'coverage'].includes(entry.name)) continue;
    const absolute = path.join(folder, entry.name);
    if (entry.isDirectory()) walk(absolute);
    else files[path.relative(root, absolute).split(path.sep).join('/')] = fs.readFileSync(absolute, 'utf8');
  }
}
walk(root);
const ordered = {'README.md':files['README.md'], 'API-CONTRACT.md':files['API-CONTRACT.md'], ...files};
fs.writeFileSync(path.resolve(__dirname, '../assets/angular-project.js'),
  '/* Generated by node scripts/bundle-angular-project.cjs. Edit examples/student-directory instead. */\n' +
  "'use strict';\nwindow.ANGULAR_PROJECT = " + JSON.stringify(ordered, null, 2) + ';\n');
console.log(`Bundled ${Object.keys(ordered).length} Student Directory files.`);
