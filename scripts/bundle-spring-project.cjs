// Rebuild the offline downloadable API source after editing the example.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../examples/spring-student-api');
const files={};
function walk(folder){
  for(const entry of fs.readdirSync(folder,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))){
    if(['target','.idea','.git'].includes(entry.name))continue;
    const absolute=path.join(folder,entry.name);
    if(entry.isDirectory())walk(absolute);
    else files[path.relative(root,absolute).split(path.sep).join('/')]=fs.readFileSync(absolute,'utf8');
  }
}
walk(root);
const ordered={'README.md':files['README.md'],'API-CONTRACT.md':files['API-CONTRACT.md'],...files};
fs.writeFileSync(path.resolve(__dirname,'../assets/spring-project.js'),
  "/* Generated by node scripts/bundle-spring-project.cjs. Edit examples/spring-student-api instead. */\n'use strict';\nwindow.SPRING_PROJECT = "+JSON.stringify(ordered,null,2)+';\n');
console.log(`Bundled ${Object.keys(ordered).length} Spring Student API files.`);
