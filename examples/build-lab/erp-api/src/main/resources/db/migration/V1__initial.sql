CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  price_minor BIGINT NOT NULL CHECK (price_minor >= 0 AND price_minor <= 100000000),
  stock BIGINT NOT NULL CHECK (stock >= 0 AND stock <= 1000000)
);
CREATE TABLE purchase_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED')),
  total_minor BIGINT NOT NULL CHECK (total_minor >= 0),
  created_at VARCHAR(40) NOT NULL,
  actor VARCHAR(80) NOT NULL
);
CREATE TABLE request_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES purchase_requests(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL CHECK (quantity > 0 AND quantity <= 1000),
  unit_price_minor BIGINT NOT NULL CHECK (unit_price_minor >= 0),
  UNIQUE (request_id, product_id)
);
CREATE TABLE audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES purchase_requests(id),
  action VARCHAR(40) NOT NULL,
  actor VARCHAR(80) NOT NULL,
  occurred_at VARCHAR(40) NOT NULL
);
